"""Build a standalone browser dataset from the roster and curated source facts."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "public/assets/js/attack-speed-data.js"


def build():
    data = json.loads((ROOT / "data/attack_speed_models.json").read_text(encoding="utf-8"))
    roster = json.loads((ROOT / "data/crawled_heroes.json").read_text(encoding="utf-8"))
    ids = {hero["id"] for hero in roster}
    mapped = {}
    for model, heroes in data.pop("groups").items():
        if model not in {*data["models"], "none", "unknown"}:
            raise ValueError(f"Unknown mapping group: {model}")
        for hero_id in heroes:
            if hero_id not in ids or hero_id in mapped:
                raise ValueError(f"Unknown or duplicate mapping: {hero_id}")
            mapped[hero_id] = model
    overrides = data.pop("overrides")
    if set(overrides) - ids:
        raise ValueError("Overrides contain unknown hero IDs")
    models = data["models"]
    sources = {source["id"] for source in data["sources"]}
    if len(sources) != len(data["sources"]):
        raise ValueError("Duplicate source IDs")
    for name, model in models.items():
        model["sources"] = data["model_sources"][name]
        if set(model["sources"]) - sources:
            raise ValueError(f"Unknown sources for model: {name}")
        thresholds = model["thresholds"]
        if thresholds[0] != 0 or any(a >= b for a, b in zip(thresholds, thresholds[1:])):
            raise ValueError(f"Unordered thresholds: {name}")
        model["rows"] = [{"percent": value, "frames": model["start_frame"] - i,
                          "sources": ["bahamut2024"] if name == "F" and model["start_frame"] - i > 19 else model["sources"]}
                         for i, value in enumerate(thresholds)]
        del model["thresholds"], model["start_frame"]
    heroes = []
    for hero in roster:
        model = mapped.get(hero["id"], "unknown")
        form = {"label": "Đánh thường", "model": model if model in models else None}
        if model not in models:
            form["status"] = model
        entry = {key: hero[key] for key in ("id", "name", "avatar")}
        entry.update({"forms": [form], "note": "", "evidence": data["hero_evidence"].get(hero["id"], ["fb2026"])})
        if set(entry["evidence"]) - sources:
            raise ValueError(f"Unknown sources for hero: {hero['id']}")
        if model == "unknown":
            entry["note"] = "Chưa có model được xác minh trong bảng nguồn; không tự gán theo vai trò hoặc tướng tương tự."
        if model == "none":
            entry["note"] = "Không áp dụng breakpoint tốc đánh thường theo nguồn. Chỉ số tốc đánh có thể tương tác riêng với nội tại; không suy ra rằng tốc đánh hoàn toàn vô ích."
        entry.update(overrides.get(hero["id"], {}))
        for variant in entry["forms"]:
            if variant["model"] is not None and variant["model"] not in models:
                raise ValueError(f"Unknown model for {hero['id']}")
        heroes.append(entry)
    data["heroes"] = heroes
    del data["model_sources"], data["hero_evidence"]
    OUTPUT.write_text("// Generated by scripts/build_attack_speed_data.py; edit data/attack_speed_models.json.\n"
                      "window.ATTACK_SPEED_DATA = " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n",
                      encoding="utf-8")
    print(f"OK: {len(heroes)} heroes, {len(models)} models -> {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    build()
